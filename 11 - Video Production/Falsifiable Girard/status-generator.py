"""Build `Episode Status.md` from the season documents.

    python3 status-generator.py

Everything in the output is read out of the research docs, so it cannot drift
from them. Re-run it after any edit, the same way you re-run audit.py.

It reports per episode: speakable length, the device, both anchors, and which of
the six register rules are present. It has no opinions; the judgement calls live
in the prose sections at the top, which are maintained by hand.
"""

import glob
import os
import re
import statistics

DIR = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(DIR, "Episode Status.md")
WPM = 135

RULES = {
    "collect": r"^## (Collecting|Where we are|Why this episode is here|Start by collecting)",
    "device": None,   # handled by has_device()
    "char": r"^## The character|character version|Second anchor|character anchor",
    "clin": r"^## The clinical|clinical version|clinical anchor|it is clinical",
    "falsif": r"^## What would count against|^## What this round can and cannot|^## Do not resolve",
    "hand": r"^## Handing off|^## How to end|^## Closing the season|^## What comes next|^## What to do with your face",
}


def first_bold(block, kind):
    """The anchor's name: the first bolded phrase inside its own section.

    Scoped to the section so it cannot wander into the next heading and pick up
    an unrelated bold, which it did for S1E10 before this was fixed.
    """
    m = re.search(rf"^## The {kind}[^\n]*$", block, re.M)
    if m:
        section = block[m.end():]
        nxt = re.search(r"^## ", section, re.M)
        if nxt:
            section = section[:nxt.start()]
        b = re.search(r"\*\*(.+?)\*\*", section, re.S)
        if b:
            return re.sub(r"\s+", " ", b.group(1)).strip(" .:*")[:52]
    # inline forms: "The clinical version: ..." / "Second anchor: ..."
    if kind == "character":
        alt = r"\*\*(?:Second anchor|The character version)[:,]?\s*(.+?)\*\*"
    else:
        alt = r"\*\*The clinical version[^*]*\*\*[,.]?\s*(?:which[^.]*\.\s*)?(.{0,60}?)[.\n]"
    m = re.search(alt, block, re.S)
    if m:
        return re.sub(r"\s+", " ", m.group(1)).strip(" .:*")[:52]
    return ""


def has_device(block):
    """A device is something you reason from on screen: a named device section,
    a table, or a code/diagram block. Heading text alone is too varied."""
    return bool(re.search(r"^## The device", block, re.M)
                or re.search(r"^\|", block, re.M)
                or "```" in block)


def speakable(block):
    b = re.sub(r"^\|.*$", "", block, flags=re.M)
    b = re.sub(r"```.*?```", "", b, flags=re.S)
    b = re.sub(r"^\s*_{3,}\s*$", "", b, flags=re.M)
    b = re.sub(r"^## Questions.*", "", b, flags=re.S | re.M)
    return len(b.split())


def main():
    seasons = []
    for f in sorted(glob.glob(os.path.join(DIR, "Research", "*.md"))):
        s = int(re.search(r"Season (\d)", os.path.basename(f)).group(1))
        title = re.search(r"Season \d — (.+)\.md", os.path.basename(f)).group(1)
        text = open(f, encoding="utf-8").read()
        eps = []
        for b in re.split(r"^@@ ", text, flags=re.M)[1:]:
            head = b.split("\n")[0]
            if not head.startswith("EPISODE"):
                continue
            n = int(re.match(r"EPISODE (\d+)", head).group(1))
            w = speakable(b)
            eps.append(dict(
                n=n,
                title=re.sub(r"^EPISODE \d+ — ", "", head).strip(),
                w=w,
                mins=round(w / WPM, 1),
                char=first_bold(b, "character"),
                clin=first_bold(b, "clinical"),
                nums=len(set(re.findall(r"\b\d[\d,]*\.?\d*%?\b", b))),
                rules="".join(
                    ("+" if (has_device(b) if k == "device"
                             else re.search(rx, b, re.M | re.I)) else
                     ("n" if (k == "collect" and n == 1) else "-"))
                    for k, rx in RULES.items()),
            ))
        seasons.append((s, title, eps))

    allw = [e["w"] for _, _, eps in seasons for e in eps]
    n_eps = len(allw)

    L = []
    L.append("# Episode Status — Seasons 1 to 3\n")
    L.append("Generated by `status-generator.py` from the season documents. "
             "**Re-run it after any edit.** Every number here is read out of the "
             "research files, so this page cannot drift from them.\n")
    L.append("---pagebreak---\n")
    L.append("@@ THE STATE\n")
    L.append("## Totals\n")
    L.append("| | episodes | speakable words | minutes | median ep |")
    L.append("|---|---|---|---|---|")
    for s, title, eps in seasons:
        w = sum(e["w"] for e in eps)
        L.append(f"| **{s} {title}** | {len(eps)} | {w:,} | {round(w/WPM)} | "
                 f"{int(statistics.median([e['w'] for e in eps]))} |")
    L.append(f"| **total** | **{n_eps}** | **{sum(allw):,}** | "
             f"**{round(sum(allw)/WPM)}** | **{int(statistics.median(allw))}** |")
    L.append("")
    L.append(f"**Shortest {min(allw)}, longest {max(allw)}.** The floor is 900 "
             "and the ceiling is 1,800, both enforced by `audit.py`. The target "
             "is 1,350, which is ten minutes at 135 words a minute.\n")

    L.append("## What has been checked, and by what\n")
    L.append("| check | tool | state |")
    L.append("|---|---|---|")
    L.append("| declared episode count matches the blocks | `audit.py` [1] | clean |")
    L.append("| episode numbers contiguous | `audit.py` [2] | clean |")
    L.append("| every cross-reference resolves | `audit.py` [3] | clean |")
    L.append("| **all six register rules per episode** | `audit.py` [4] | clean |")
    L.append("| length inside 900-1,800 | `audit.py` [5] | clean |")
    L.append("| bolded terms are in the glossary | `audit.py` [6] | clean |")
    L.append("| every planted number names its detonation | `audit.py` [7] | clean |")
    L.append("| numbers agree across seasons | `coherence.py` | clean |")
    L.append("| forward promises owed to unwritten seasons | `coherence.py` | tracked |")
    L.append("")
    L.append(">> **A cross-reference resolving is not the same as it being right.** "
             "`audit.py` proves the target episode exists. After any renumber, "
             "check each reference against the **title** it now points at.\n")

    L.append("## The six register rules\n")
    L.append("Read the flag column as six slots in this order:\n")
    L.append("| slot | rule |")
    L.append("|---|---|")
    for k, label in zip(RULES, [
            "opens by collecting the previous episode",
            "has a device, not just prose",
            "character anchor, for the audience",
            "clinical anchor, for you",
            "what would count against this",
            "hands off by naming the next episode"]):
        L.append(f"| `{k}` | {label} |")
    L.append("")
    L.append("`+` present, `-` absent. **Episode 1 of a season is exempt from "
             "collecting.** Questions with no answers in the document are rule "
             "six and are enforced separately by `audit.py`.\n")
    L.append("---pagebreak---\n")

    for s, title, eps in seasons:
        L.append(f"@@ SEASON {s} — {title.upper()}\n")
        L.append("| ep | title | words | min | flags | character anchor | clinical anchor |")
        L.append("|---|---|---|---|---|---|---|")
        for e in eps:
            L.append(f"| {e['n']} | {e['title'][:44]} | {e['w']} | {e['mins']} | "
                     f"`{e['rules']}` | {e['char']} | {e['clin']} |")
        L.append("")
        L.append("---pagebreak---\n")

    open(OUT, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {OUT}  ({n_eps} episodes, {sum(allw):,} words)")


if __name__ == "__main__":
    main()
